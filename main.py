def make_gallery_slug(title):

    slug = title.lower().strip()

    slug = re.sub(
        r"[^a-z0-9]+",
        "-",
        slug
    )

    slug = slug.strip("-")

    if not slug:
        slug = "event"

    return slug


def get_gallery_data():

    connection = get_db()

    event_cursor = db_execute(
        connection,
        """
        SELECT
            id,
            title,
            description,
            event_date,
            cover_photo,
            created_at
        FROM gallery_events
        ORDER BY id DESC
        """
    )

    events = rows_as_dict(
        event_cursor.fetchall()
    )

    result = []

    for event in events:

        photo_cursor = db_execute(
            connection,
            """
            SELECT
                id,
                event_id,
                photo_url,
                public_id,
                created_at
            FROM gallery_photos
            WHERE event_id = ?
            ORDER BY id DESC
            """,
            (event["id"],)
        )

        photos = rows_as_dict(
            photo_cursor.fetchall()
        )

        event["photos"] = photos
        event["photo_count"] = len(photos)

        result.append(event)

    connection.close()

    return result


