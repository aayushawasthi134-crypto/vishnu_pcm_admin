# UPLOAD MULTIPLE GALLERY PHOTOS
# =========================================================

@app.post("/api/admin/gallery/{event_id}/photos")
async def upload_gallery_photos(

    event_id: int,
    photos: list[UploadFile] = File(...),
    _: bool = Depends(check_auth)
):

    connection = get_db()

    event_cursor = db_execute(
        connection,
        """
        SELECT *
        FROM gallery_events
        WHERE id = ?
        """,
        (event_id,)
    )

    event = event_cursor.fetchone()

    if not event:

        connection.close()

        raise HTTPException(
            status_code=404,
            detail="Gallery event not found"
        )

    event_title = (
        event["title"]
        if isinstance(event, dict)
        else event[1]
    )

    slug = make_gallery_slug(
        event_title
    )

    uploaded = []

    allowed_extensions = [
        ".jpg",
        ".jpeg",
        ".png",
        ".webp"
    ]

    for photo in photos:

        if not photo or not photo.filename:
            continue

        extension = Path(
            photo.filename
        ).suffix.lower()

        if extension not in allowed_extensions:

            continue

        photo_url, public_id = (
            upload_gallery_image_to_cloudinary(
                photo,
                f"vishnu-pcm/gallery/{slug}"
            )
        )

        cursor = db_execute(
            connection,
            """
            INSERT INTO gallery_photos
            (
                event_id,
                photo_url,
                public_id
            )
            VALUES (?, ?, ?)
            RETURNING id
            """,
            (
                event_id,
                photo_url,
                public_id
            )
        )

        photo_id = get_returned_id(cursor)

        uploaded.append({
            "id": photo_id,
            "photo_url": photo_url
        })

    if uploaded:

        cover_cursor = db_execute(
            connection,
            """
            SELECT cover_photo
            FROM gallery_events
            WHERE id = ?
            """,
            (event_id,)
        )

        cover_row = cover_cursor.fetchone()

        current_cover = (
            cover_row["cover_photo"]
            if isinstance(cover_row, dict)
            else cover_row[0]
        )

        if not current_cover:

            db_execute(
                connection,
                """
                UPDATE gallery_events
                SET cover_photo = ?
                WHERE id = ?
                """,
                (
                    uploaded[0]["photo_url"],
                    event_id
                )
            )

    connection.commit()
    connection.close()

    return {
        "success": True,
        "uploaded": uploaded,
        "count": len(uploaded)
    }


