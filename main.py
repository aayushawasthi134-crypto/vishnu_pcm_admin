@app.get("/api/public")
async def public_data():
    connection = get_db()

    toppers = rows_as_dict(
        db_execute(
            connection,
            """
            SELECT *
            FROM people
            WHERE type='topper'
            ORDER BY id DESC
            """
        ).fetchall()
    )

    alumni = rows_as_dict(
        db_execute(
            connection,
            """
            SELECT *
            FROM people
            WHERE type='alumni'
            ORDER BY id DESC
            """
        ).fetchall()
    )

    testimonials = rows_as_dict(
        db_execute(
            connection,
            """
            SELECT *
            FROM testimonials
            ORDER BY id DESC
            """
        ).fetchall()
    )

    faculty = rows_as_dict(
        db_execute(
            connection,
            """
            SELECT *
            FROM faculty
            ORDER BY id DESC
            """
        ).fetchall()
    )

    connection.close()

    return {
        "toppers": toppers,
        "alumni": alumni,
        "testimonials": testimonials,
        "faculty": faculty
    }

