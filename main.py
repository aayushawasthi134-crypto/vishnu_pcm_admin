# =====================================================
# DELETE TOPPER
# =====================================================

@app.delete("/api/admin/topper/{person_id}")
async def delete_topper(
    person_id: int,
    _: bool = Depends(check_auth)
):
    connection = get_db()

    person = db_execute(
        connection,
        """
        SELECT photo
        FROM people
        WHERE id=? AND type='topper'
        """,
        (person_id,)
    ).fetchone()

    if not person:
        connection.close()
        raise HTTPException(status_code=404, detail="Topper not found")

    photo = person["photo"] if isinstance(person, dict) else person["photo"]

    if photo:
        image_path = BASE / photo.lstrip("/")
        if image_path.exists():
            image_path.unlink()

    db_execute(
        connection,
        "DELETE FROM people WHERE id=? AND type='topper'",
        (person_id,)
    )

    connection.commit()
    connection.close()

    return {"success": True}

